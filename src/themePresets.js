function createThemedVariables(base, palette) {
    const accentRgb = palette.ramp[7]
        .match(/[\da-f]{2}/gi)
        .map((part) => Number.parseInt(part, 16))
        .join(",");
    const replacements = new Map(
        rampNames.map((name, index) => [
            base[name].toLowerCase(),
            palette.base === "dark"
                ? [...palette.ramp].reverse()[index]
                : palette.ramp[index],
        ]),
    );

    const variables = Object.fromEntries(
        Object.entries(base).map(([name, originalValue]) => {
            let value = originalValue;
            for (const [source, target] of replacements) {
                value = value.replaceAll(source, target);
            }
            value = value.replace(
                /rgba\(0,\s*104,\s*255,\s*([^)]+)\)/gi,
                `rgba(${accentRgb},$1)`,
            );
            return [name, value];
        }),
    );

    neutralNames.forEach((name, index) => {
        variables[name] = palette.neutral[index];
    });

    return variables;
}

